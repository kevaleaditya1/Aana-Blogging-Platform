// Run only against the isolated fake-ID preview. All Google requests are intercepted.
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const checks = [];
const check = (name, passed) => { checks.push({ name, passed }); console.log(passed ? 'PASS' : 'FAIL', name); };
let browser;
(async () => {
    browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const context = await browser.newContext();
    let requests = 0;
    await context.route(/https:\/\/.*(googletagmanager|google-analytics|googlesyndication|doubleclick)\./, route => { requests++; return route.fulfill({ contentType: 'text/javascript', body: '// Local test stub; no collection.' }); });
    const page = await context.newPage();
    const origin = 'http://127.0.0.1:3300';
    await page.goto(origin + '/about?email=must-not-track%40example.com', { waitUntil: 'networkidle', timeout: 90000 });
    await page.getByRole('button', { name: 'Reject optional', exact: true }).waitFor();
    check('Enabled integration makes no Google request before consent', requests === 0);
    await page.getByRole('button', { name: 'Reject optional', exact: true }).click();
    await page.reload({ waitUntil: 'networkidle' });
    check('Enabled integration makes no Google request after rejection', requests === 0);
    await page.getByRole('button', { name: 'Cookie preferences', exact: true }).click();
    await page.getByRole('button', { name: 'Accept analytics', exact: true }).click();
    await page.waitForFunction(() => Boolean(window.gtag));
    await page.waitForLoadState('networkidle');
    check('Acceptance loads only the stubbed Google tag', requests === 1);
    const events = () => page.evaluate(() => (window.dataLayer || []).map(args => Array.from(args)));
    let log = await events();
    check('Manual pageview excludes query values', log.some(args => args[0] === 'event' && args[1] === 'page_view' && args[2]?.page_location === 'https://aanaa.blog/about') && !JSON.stringify(log).includes('must-not-track'));
    check('Ad storage stays denied', log.some(args => args[0] === 'consent' && args[2]?.ad_storage === 'denied'));
    await page.getByRole('link', { name: 'Contact', exact: true }).first().click();
    await page.waitForURL('**/contact');
    await page.waitForTimeout(100);
    log = await events();
    check('Client navigation records a sanitized pageview', log.some(args => args[0] === 'event' && args[1] === 'page_view' && args[2]?.page_location === 'https://aanaa.blog/contact'));
    await page.route('**/api/contact', route => route.fulfill({ contentType: 'application/json', body: '{"success":true}' }));
    const form = page.locator('main form');
    await form.getByLabel('Name', { exact: true }).fill('Consent Tester');
    await form.getByLabel('Email address', { exact: true }).fill('must-not-track@example.com');
    await form.getByLabel('Message', { exact: true }).fill('This form submission is mocked locally.');
    await form.getByRole('button', { name: 'Send message', exact: true }).click();
    await page.waitForURL('**/success/contact');
    log = await events();
    const conversions = log.filter(args => args[0] === 'event' && args[1] === 'contact_success');
    check('Confirmed operation emits one conversion without form values', conversions.length === 1 && !JSON.stringify(log).includes('must-not-track') && !JSON.stringify(log).includes('Consent Tester'));
    await page.reload({ waitUntil: 'networkidle' });
    log = await events();
    check('Success-page refresh emits no conversion', !log.some(args => args[0] === 'event' && args[1] === 'contact_success'));
    await page.evaluate(() => { document.cookie = '_ga=mock;path=/'; });
    await page.getByRole('button', { name: 'Cookie preferences', exact: true }).click();
    const before = requests;
    await page.getByRole('button', { name: 'Reject optional', exact: true }).click();
    await page.waitForLoadState('networkidle');
    check('Withdrawal reloads without reloading Google', requests === before);
    check('Withdrawal clears accessible analytics cookies', await page.evaluate(() => !document.cookie.split(';').some(cookie => cookie.trim().startsWith('_ga='))));
    fs.writeFileSync('audit/consent-results.json', JSON.stringify(checks, null, 2));
    await browser.close();
    if (checks.some(row => !row.passed)) process.exitCode = 1;
})().catch(async error => { console.error(error); fs.writeFileSync('audit/consent-results.json', JSON.stringify({ checks, error: error.message }, null, 2)); await browser?.close(); process.exitCode = 1; });

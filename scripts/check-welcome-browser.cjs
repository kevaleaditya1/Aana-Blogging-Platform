const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
let browser;
(async () => {
    browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addInitScript(() => localStorage.setItem('aana-consent-v1', 'rejected'));
    const page = await context.newPage();
    const checks = [];
    const check = (name, passed) => { checks.push({ name, passed }); console.log(passed ? 'PASS' : 'FAIL', name); };
    const origin = 'http://127.0.0.1:3200';
    let requests = 0;
    await page.route('**/api/newsletter/subscribe', async route => { requests++; await new Promise(resolve => setTimeout(resolve, 300)); await route.fulfill({ contentType: 'application/json', body: '{"success":true,"confirmationRequired":true}' }); });
    await page.goto(origin + '/about', { waitUntil: 'networkidle' });
    const form = page.locator('footer form');
    await form.getByLabel('Email address', { exact: true }).fill('mock-reader@example.com');
    await form.getByRole('button', { name: 'Subscribe to updates' }).click();
    check('Welcome request exposes pending state', await form.getAttribute('aria-busy') === 'true');
    await page.waitForURL('**/success/newsletter');
    check('Request goes to dedicated success URL without email', !page.url().includes('mock-reader'));
    check('Feedback asks for email confirmation', await page.getByText(/Use its confirmation link to activate/).isVisible());
    check('Pending request does not claim active subscription', !(await page.getByRole('heading', { name: 'You’re subscribed', exact: true }).count()));
    await page.reload({ waitUntil: 'networkidle' });
    check('Success refresh does not resend welcome', requests === 1);
    let confirmations = 0;
    page.on('request', request => { if (request.url().endsWith('/api/newsletter/confirm') && request.method() === 'POST') confirmations++; });
    await page.goto(origin + '/newsletter/confirm/invalid-local-test-token', { waitUntil: 'networkidle' });
    check('Opening link does not confirm subscription', confirmations === 0);
    check('Confirmation page is noindex', (await page.locator('meta[name=robots]').getAttribute('content')).includes('noindex'));
    for (const width of [320, 390, 768, 1440]) {
        await page.setViewportSize({ width, height: 900 });
        check(`Confirmation layout ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    }
    const invalid = await context.request.post(origin + '/api/newsletter/confirm', { data: { token: 'invalid' } });
    check('Real handler rejects invalid token before writes', invalid.status() === 400);
    const safeGet = await context.request.get(origin + '/api/newsletter/confirm');
    check('GET cannot activate a subscription', safeGet.status() === 405);
    await page.route('**/api/newsletter/confirm', route => route.fulfill({ status: 400, contentType: 'application/json', body: '{"error":"This confirmation link is expired. Request a new one."}' }));
    await page.getByRole('button', { name: 'Confirm my subscription', exact: true }).click();
    await page.locator('main').getByRole('alert').waitFor();
    check('Expired-link error is accessible and retryable', await page.getByRole('button', { name: 'Confirm my subscription', exact: true }).isEnabled());
    await page.unroute('**/api/newsletter/confirm');
    await page.route('**/api/newsletter/confirm', async route => { await new Promise(resolve => setTimeout(resolve, 300)); await route.fulfill({ contentType: 'application/json', body: '{"success":true,"newlyConfirmed":true}' }); });
    await page.getByRole('button', { name: 'Confirm my subscription', exact: true }).click();
    check('Confirmation pending disables duplicate clicks', await page.getByRole('button', { name: 'Confirming…' }).isDisabled());
    await page.getByRole('heading', { name: 'You’re subscribed', exact: true }).waitFor();
    await page.waitForURL('**/success/newsletter-confirmed');
    check('Only confirmed operation opens clean success URL', !page.url().includes('test-token'));
    check('Confirmed feedback is explicit', await page.getByText('Your email address is verified. You can now receive Aana newsletters, and each email includes an unsubscribe link.').isVisible());
    await page.screenshot({ path: 'audit/welcome-confirmation-desktop.png' });
    fs.writeFileSync('audit/welcome-browser-tests.json', JSON.stringify(checks, null, 2));
    await browser.close();
    if (checks.some(row => !row.passed)) process.exitCode = 1;
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
